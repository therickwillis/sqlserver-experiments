CREATE TABLE [dbo].[ApiKey]
(
  [Id] UNIQUEIDENTIFIER NOT NULL PRIMARY KEY CONSTRAINT DF_ApiKey_Id DEFAULT NEWSEQUENTIALID(),
  [KeyHash] NVARCHAR(255) NOT NULL,
  [Description] NVARCHAR(500) NULL,
  [CreatedAt] DATETIME2 NOT NULL CONSTRAINT DF_ApiKey_CreatedAt DEFAULT GETUTCDATE(),
  [ExpiresAt] DATETIME2 NULL,
  [LastUsedAt] DATETIME2 NULL,
  [IsActive] BIT NOT NULL CONSTRAINT DF_ApiKey_IsActive DEFAULT 1
)
