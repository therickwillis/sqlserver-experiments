CREATE TABLE [dbo].[MatingPair]
(
  [Id] UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
  [BeeVariant1Id] UNIQUEIDENTIFIER NOT NULL,
  [BeeVariant2Id] UNIQUEIDENTIFIER NOT NULL,
  FOREIGN KEY (BeeVariant1Id) REFERENCES BeeVariant(Id),
  FOREIGN KEY (BeeVariant2Id) REFERENCES BeeVariant(Id)
)
