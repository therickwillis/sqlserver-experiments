CREATE TABLE [dbo].[MatingBaby]
(
  [Id] UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
  [MatingPairId] UNIQUEIDENTIFIER NOT NULL,
  [BabyBeeVariantId] UNIQUEIDENTIFIER NOT NULL,
  [Probability] FLOAT NOT NULL,
  FOREIGN KEY (MatingPairId) REFERENCES MatingPair(Id),
  FOREIGN KEY (BabyBeeVariantId) REFERENCES BeeVariant(Id)
)
